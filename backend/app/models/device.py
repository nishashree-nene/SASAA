"""
SASAA – Device Registration Models
=====================================
Two tables for push notification delivery:

  device_tokens          – Firebase Cloud Messaging tokens (Android)
  web_push_subscriptions – Web Push API subscriptions (browser)

A user can have multiple devices and browsers registered simultaneously.
When we send a push notification, we fan-out to all active registrations.
"""

import uuid
from typing import Optional

from sqlalchemy import Boolean, ForeignKey, String, Text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin


class DeviceToken(Base, TimestampMixin):
    """
    Firebase Cloud Messaging token for an Android device.

    FCM tokens change periodically. When a new token is received,
    the old one for the same device is replaced (upsert by device_id).
    is_active=False means the token has expired or the app was uninstalled.
    """
    __tablename__ = "device_tokens"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # The FCM token string (can be long – use Text)
    fcm_token: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        comment="Firebase Cloud Messaging registration token",
    )

    # A stable identifier for the physical device
    device_id: Mapped[Optional[str]] = mapped_column(
        String(255),
        nullable=True,
        comment="Android device ID (used to replace old tokens for the same device)",
    )

    device_name: Mapped[Optional[str]] = mapped_column(
        String(255),
        nullable=True,
        comment="Human-readable device name e.g. 'Pixel 7 Pro'",
    )

    is_active: Mapped[bool] = mapped_column(
        Boolean,
        default=True,
        nullable=False,
        comment="False when the token has expired or the app was uninstalled",
    )

    def __repr__(self) -> str:
        return f"<DeviceToken user_id={self.user_id} active={self.is_active}>"


class WebPushSubscription(Base, TimestampMixin):
    """
    Web Push API subscription for a browser session.

    The subscription object (endpoint + keys) is generated by the browser
    and sent to the backend via POST /notifications/register-device.
    It is stored as JSON because its structure varies slightly between browsers.
    """
    __tablename__ = "web_push_subscriptions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # The full subscription object from browser's PushManager.subscribe()
    subscription_json: Mapped[dict] = mapped_column(
        JSONB,
        nullable=False,
        comment="Full Web Push subscription object: {endpoint, keys: {p256dh, auth}}",
    )

    # The endpoint URL is the unique identifier for this subscription
    endpoint: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        comment="Push service endpoint URL",
    )

    is_active: Mapped[bool] = mapped_column(
        Boolean,
        default=True,
        nullable=False,
    )

    browser: Mapped[Optional[str]] = mapped_column(
        String(100),
        nullable=True,
        comment="Browser name for the session list display",
    )

    def __repr__(self) -> str:
        return f"<WebPushSubscription user_id={self.user_id} active={self.is_active}>"
